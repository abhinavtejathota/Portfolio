import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { encodePortfolio, resolveEncodeKey } from "./lib/portfolio-crypto.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const privatePath = join(root, "data", "portfolio.private.json");
const outputPath = join(root, "src", "data", "portfolio.bundle.json");
const keyPath = join(root, "src", "data", "decodeKey.js");

function writeDecodeKey(secret) {
  writeFileSync(
    keyPath,
    `// Auto-generated by npm run data:encode — keep in sync with portfolio.bundle.json\nexport const DECODE_KEY = ${JSON.stringify(secret)};\n`,
    "utf8",
  );
}

if (!existsSync(privatePath)) {
  if (existsSync(outputPath) && existsSync(keyPath)) {
    console.log("Skipping encode: using committed portfolio.bundle.json + decodeKey.js");
    process.exit(0);
  }

  console.error("\nMissing data/portfolio.private.json");
  console.error("Create that file, run npm run data:encode locally, then commit the bundle.\n");
  process.exit(1);
}

const source = readFileSync(privatePath, "utf8");
let parsed;

try {
  parsed = JSON.parse(source);
} catch {
  console.error("data/portfolio.private.json is not valid JSON.");
  process.exit(1);
}

const secret = resolveEncodeKey();
const bundle = encodePortfolio(parsed, secret);
writeFileSync(outputPath, `${JSON.stringify(bundle, null, 2)}\n`, "utf8");
writeDecodeKey(secret);

console.log("Wrote obfuscated bundle -> src/data/portfolio.bundle.json");
console.log("Wrote decode key       -> src/data/decodeKey.js");
